def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("root", help="知识库根目录（不存在则创建）")
    ap.add_argument("--name", default="毕业论文", help="项目名称")
    ap.add_argument("--deadline", default="待定", help="学校最终提交日期 YYYY-MM-DD")
    args = ap.parse_args()

    root = Path(args.root)
    if root.exists() and any(root.iterdir()):
        print(f"提示：{root} 非空，已有文件将被跳过，不会覆盖。")

    for d in DIRS:
        (root / d).mkdir(parents=True, exist_ok=True)

    created, skipped = [], []
    for rel, content in templates(args.name, args.deadline).items():
        p = root / rel
        if p.exists():
            skipped.append(rel)
            continue
        p.write_text(content, encoding="utf-8")
        created.append(rel)

    print(f"已创建 {len(created)} 个模板文件，跳过 {len(skipped)} 个已存在文件。")
    for rel in created:
        print("  +", rel)
    from build_dashboard import generate
    generate(root)
    print("\n下一步：开始建档访谈——填写 01-要求与规范 下的使用者画像、导师方向和学校要求。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
